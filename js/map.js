  /** Total stars earned inside a chapter (delegates to the story module). */
  function worldStars(save, ch) {
    try {
      if (ST && ST.worldStars && ST.WORLDS && ST.WORLDS[ch.id - 1]) {
        return ST.worldStars(save, ST.WORLDS[ch.id - 1]);
      }
    } catch (e) {}
    var total = 0;
    if (!save || !save.best) return 0;
    for (var n = ch.startLevel; n <= ch.endLevel; n++) {
      var b = save.best[n];
      if (b && b.stars) total += b.stars;
    }
    return total;
  }

