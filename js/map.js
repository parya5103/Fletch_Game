  /**
   * Visual state of a level node, strictly derived from the real save:
   * locked  -> above save.unlocked (original progression rules)
   * completed -> cleared with at least 1 star
   * current -> the furthest active level (save.cur or save.unlocked)
   * open    -> unlocked and replayable, no stars yet
   */
  function nodeStateFor(level, save, focus) {
    save = save || {};
    level = clampLevel(level);
    var unlocked = Math.max(1, Math.min(TOTAL_LEVELS, Math.floor(Number(save.unlocked) || 1)));
    if (level > unlocked) return 'locked';
    var b = save.best && save.best[level];
    if (b && b.stars > 0) return 'completed';
    if (focus && level === clampLevel(focus)) return 'current';
    return 'open';
  }

